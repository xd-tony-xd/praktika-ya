create extension if not exists pgcrypto with schema extensions;

-- ---------------------------------------------------------------------
--  PERFILES (uno por usuario de auth: admin o empresa)
-- ---------------------------------------------------------------------
create table public.perfiles (
  id          uuid primary key references auth.users(id) on delete cascade,
  rol         text not null default 'empresa' check (rol in ('admin', 'empresa')),
  nombre      text,
  foto_perfil text,
  creado_en   timestamptz not null default now()
);

-- ---------------------------------------------------------------------
--  EMPRESAS
-- ---------------------------------------------------------------------
create table public.empresas (
  id                bigint generated by default as identity primary key,
  user_id           uuid unique references auth.users(id) on delete cascade,
  nombre_comercial  text not null check (char_length(nombre_comercial) between 2 and 180),
  ruc               text not null unique check (ruc ~ '^[0-9]{11}$'),
  sector            text not null default 'GENERAL',
  correo_contacto   text not null,
  telefono          text check (telefono is null or telefono ~ '^[0-9]{9}$'),
  direccion         text,
  foto_perfil       text,          -- URL pública (bucket "publico")
  ficha_ruc         text,          -- ruta en bucket privado "documentos"
  dni_frente        text,
  dni_reverso       text,
  foto_selfie       text,
  ruc_verificado    boolean not null default false,
  estado            text not null default 'pendiente' check (estado in ('pendiente', 'aprobado', 'bloqueado')),
  -- Política de transparencia (Sello)
  postulacion_ciega             boolean not null default true,
  comunica_motivo_no_seleccion  boolean not null default false,
  creado_en         timestamptz not null default now()
);
create unique index empresas_correo_uq on public.empresas (lower(correo_contacto));
create index empresas_estado_idx on public.empresas (estado);

-- ---------------------------------------------------------------------
--  CARRERAS
-- ---------------------------------------------------------------------
create table public.carreras (
  id     bigint generated by default as identity primary key,
  nombre text not null check (char_length(trim(nombre)) between 2 and 180)
);
create unique index carreras_nombre_uq on public.carreras (lower(nombre));

-- ---------------------------------------------------------------------
--  VACANTES
-- ---------------------------------------------------------------------
create table public.vacantes (
  id                 bigint generated by default as identity primary key,
  empresa_id         bigint not null references public.empresas(id) on delete cascade,
  titulo_puesto      text not null check (char_length(titulo_puesto) between 3 and 190),
  descripcion_puesto text not null,
  requisitos_raw     text not null,
  modalidad          text not null default 'Presencial' check (modalidad in ('Presencial', 'Remoto', 'Híbrido')),
  ubicacion          text,
  estado             text not null default 'abierta' check (estado in ('abierta', 'cerrada')),
  fecha_limite       date,
  fecha_publicacion  timestamptz not null default now(),
  creado_en          timestamptz not null default now(),
  actualizado_en     timestamptz not null default now()
);
create index vacantes_empresa_estado_idx on public.vacantes (empresa_id, estado);
create index vacantes_fecha_idx on public.vacantes (fecha_limite);

create table public.vacante_carreras (
  vacante_id bigint not null references public.vacantes(id) on delete cascade,
  carrera_id bigint not null references public.carreras(id) on delete cascade,
  primary key (vacante_id, carrera_id)
);
create index vacante_carreras_carrera_idx on public.vacante_carreras (carrera_id);

-- ---------------------------------------------------------------------
--  POSTULACIONES
-- ---------------------------------------------------------------------
create table public.postulaciones (
  id                      bigint generated by default as identity primary key,
  vacante_id              bigint not null references public.vacantes(id) on delete cascade,
  dni                     text not null check (dni ~ '^[0-9]{8}$'),
  nombre_completo         text not null check (char_length(nombre_completo) between 3 and 190),
  correo_estudiante       text not null,
  celular                 text check (celular is null or celular ~ '^[0-9]{9}$'),
  cv_path                 text not null,                 -- ruta en bucket privado "cvs"
  match_porcentaje        numeric(5,2) not null default 0 check (match_porcentaje between 0 and 100),
  ia_analisis_descripcion text,
  ia_modelo               text,
  analizado_en            timestamptz,
  estado_postulacion      text not null default 'en_espera' check (estado_postulacion in ('en_espera', 'Apto', 'No Apto')),
  notificacion_leida      boolean not null default false,
  notificado_en           timestamptz,                  -- último correo enviado al postulante
  -- CV por voz (aprobado por el postulante; el audio NO se guarda)
  voz_transcripcion       text,
  voz_estudios            text[],
  voz_experiencia         text[],
  voz_habilidades         text[],
  consentimiento_en       timestamptz not null default now(),
  fecha_postulacion       timestamptz not null default now(),
  constraint postulacion_dni_uq unique (vacante_id, dni)
);
create unique index postulacion_correo_uq on public.postulaciones (vacante_id, lower(correo_estudiante));
create index postulacion_estado_idx on public.postulaciones (estado_postulacion);
create index postulacion_fecha_idx on public.postulaciones (fecha_postulacion);

-- ---------------------------------------------------------------------
--  CONFIGURACIÓN GLOBAL (clave/valor)
-- ---------------------------------------------------------------------
create table public.configuracion (
  clave          text primary key,
  valor          text,
  actualizado_en timestamptz not null default now()
);

-- ---------------------------------------------------------------------
--  CRÉDITOS IA Y PAGOS (Stripe)
-- ---------------------------------------------------------------------
create table public.creditos_empresa (
  empresa_id     bigint primary key references public.empresas(id) on delete cascade,
  saldo          integer not null default 0 check (saldo >= 0),
  actualizado_en timestamptz not null default now()
);

create table public.paquetes_creditos (
  id              bigint generated by default as identity primary key,
  nombre          text not null unique check (char_length(nombre) between 1 and 100),
  creditos        integer not null check (creditos between 1 and 100000),
  costo_base      numeric(10,2) not null check (costo_base >= 0.01),
  margen_utilidad numeric(7,2) not null default 100 check (margen_utilidad between 0 and 10000),
  activo          boolean not null default true,
  orden           integer not null default 0,
  precio_unitario numeric(12,2) generated always as (round(costo_base * (1 + margen_utilidad / 100), 2)) stored,
  precio_total    numeric(14,2) generated always as (round(round(costo_base * (1 + margen_utilidad / 100), 2) * creditos, 2)) stored,
  creado_en       timestamptz not null default now(),
  actualizado_en  timestamptz not null default now()
);

create table public.movimientos_creditos (
  id             bigint generated by default as identity primary key,
  empresa_id     bigint not null references public.empresas(id) on delete cascade,
  postulacion_id bigint references public.postulaciones(id) on delete set null,
  tipo           text not null check (tipo in ('compra', 'reserva', 'consumo', 'reembolso', 'bonificacion')),
  creditos       integer not null check (creditos > 0),
  estado         text not null default 'completado' check (estado in ('pendiente', 'completado', 'fallido')),
  referencia     text unique,
  descripcion    text,
  creado_en      timestamptz not null default now()
);
create index movimientos_empresa_fecha_idx on public.movimientos_creditos (empresa_id, creado_en desc);
-- Evita dos análisis simultáneos de la misma postulación (doble clic, dos pestañas)
create unique index movimientos_reserva_pendiente_uq
  on public.movimientos_creditos (postulacion_id) where estado = 'pendiente';

create table public.pagos_stripe (
  id                         bigint generated by default as identity primary key,
  empresa_id                 bigint not null references public.empresas(id) on delete cascade,
  session_id                 text not null unique,
  payment_intent_id          text,
  monto_centimos             integer not null check (monto_centimos > 0),
  costo_estimado_centimos    integer not null default 0,
  utilidad_estimada_centimos integer not null default 0,
  moneda                     text not null default 'PEN',
  creditos                   integer not null check (creditos > 0),
  paquete_nombre             text not null,
  estado                     text not null default 'pendiente' check (estado in ('pendiente', 'pagado', 'fallido')),
  creado_en                  timestamptz not null default now(),
  pagado_en                  timestamptz
);
create index pagos_empresa_fecha_idx on public.pagos_stripe (empresa_id, creado_en desc);

-- ---------------------------------------------------------------------
--  SELLO DE TRANSPARENCIA (registro inmutable encadenado por hash)
-- ---------------------------------------------------------------------
create table public.sellos (
  id                   bigint generated by default as identity primary key,
  empresa_id           bigint not null references public.empresas(id) on delete cascade,
  sello_otorgado       boolean not null,
  criterios_cumplidos  text[] not null default '{}',
  criterios_pendientes text[] not null default '{}',
  detalle              jsonb not null default '{}'::jsonb,
  huella               text not null unique,     -- SHA-256 del registro
  huella_anterior      text,                     -- encadena con el registro previo de la empresa
  emitido_en           timestamptz not null default now()
);
create index sellos_empresa_fecha_idx on public.sellos (empresa_id, emitido_en desc);

-- ---------------------------------------------------------------------
--  LÍMITE DE USO DE ENDPOINTS PÚBLICOS (anti abuso)
-- ---------------------------------------------------------------------
create table public.uso_publico (
  id        bigint generated by default as identity primary key,
  accion    text not null,
  clave     text not null,
  creado_en timestamptz not null default now()
);
create index uso_publico_idx on public.uso_publico (accion, clave, creado_en desc);
